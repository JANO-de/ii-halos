#!/usr/bin/env python3
import argparse, json, os

def write_all(file_path, monitors):
    lines = ["-- Generated by ii settings. Manual changes may be overwritten.\n", "\n"]
    for m in monitors:
        name = m["name"]
        mode = m.get("mode", "preferred")
        position = m.get("position", "auto")
        scale = m.get("scale", 1)
        transform = m.get("transform", 0)
        parts = [f'output = "{name}"', f'mode = "{mode}"', f'position = "{position}"', f'scale = {scale}']
        if transform:
            parts.append(f'transform = {transform}')
        lines.append("hl.monitor({ " + ", ".join(parts) + " })\n")
    os.makedirs(os.path.dirname(os.path.abspath(file_path)), exist_ok=True)
    with open(file_path, "w") as f:
        f.writelines(lines)

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--file", required=True)
    p.add_argument("--all", required=True)
    args = p.parse_args()
    monitors = json.loads(args.all)
    write_all(os.path.expanduser(args.file), monitors)

if __name__ == "__main__":
    main()
